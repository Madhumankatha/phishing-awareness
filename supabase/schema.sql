-- Authorized awareness simulation events only. Do not collect credentials.
create table if not exists public.click_events (
  id bigint generated by default as identity primary key,
  participant_name text not null check (length(participant_name) <= 100),
  occurred_at timestamptz not null default now()
);

alter table public.click_events enable row level security;
-- No public/client access policies are intentionally created.
-- Writes/reads are performed server-side using the service role key.
